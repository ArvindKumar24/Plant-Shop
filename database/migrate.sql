-- ============================================================
-- PAGES TABLE
-- ============================================================

CREATE TABLE IF NOT EXISTS pages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(50) NOT NULL UNIQUE,
    title VARCHAR(150) NOT NULL,
    content TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);


